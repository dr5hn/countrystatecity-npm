/**
 * Generates live, interactive location UI: a type-ahead autocomplete field
 * and a cascading country/state/city picker, backed by the real
 * `csc.search.autocomplete()` endpoint at runtime — unlike react-dropdown.ts,
 * nothing is pre-fetched or baked in at generation time.
 */

export type GeneratorTarget = 'nextjs' | 'react-browser';

/**
 * Shown before any react-browser file is written, and repeated verbatim in
 * the generated README so the warning survives past the initial CLI run.
 */
export const BROWSER_KEY_WARNING =
  'Your API key will be visible in browser JavaScript and network requests — ' +
  'there is no server to keep it secret. Before using this component, create a ' +
  'key in your CSC dashboard restricted to your approved website origin(s). ' +
  'Never use an unrestricted/server key here.';

const AUTOCOMPLETE_ROUTE_PATH = 'app/api/csc-search/route.ts';
const TRACKED_PRICING_URL =
  'https://countrystatecity.in/pricing?source=cli&campaign=location_components&package=cli';
const TRACKED_SIGNUP_URL =
  'https://app.countrystatecity.in?source=cli&campaign=location_components&package=cli';

/**
 * Next.js Route Handler that holds the real API key server-side and proxies
 * to `csc.search.autocomplete()`. Shared by both the autocomplete and
 * location-picker Next.js generators since it's the same one endpoint
 * called with different `type`/`country`/`state` filters.
 */
export function generateAutocompleteRoute(): string {
  return `// ${AUTOCOMPLETE_ROUTE_PATH}
// Generated by @countrystatecity/cli
//
// Keeps CSC_API_KEY server-side. The browser never sees it — it only ever
// talks to this same-origin route.

import { NextRequest, NextResponse } from 'next/server';
import {
  createCSCClient,
  ValidationError,
  AuthenticationError,
  FeatureRestrictedError,
  RateLimitError,
} from '@countrystatecity/sdk';
import type { SearchResultType } from '@countrystatecity/sdk';

export async function GET(request: NextRequest) {
  const apiKey = process.env.CSC_API_KEY;
  if (!apiKey) {
    return NextResponse.json(
      { error: 'CSC_API_KEY is not configured on the server. See .env.example.' },
      { status: 500 }
    );
  }

  const searchParams = request.nextUrl.searchParams;
  const query = searchParams.get('query') ?? '';
  const type = (searchParams.get('type') ?? 'city') as SearchResultType;
  const country = searchParams.get('country') ?? undefined;
  const state = searchParams.get('state') ?? undefined;

  const csc = createCSCClient({ apiKey });

  try {
    const { data } = await csc.search.autocomplete({ query, type, country, state, limit: 10 });
    return NextResponse.json(data);
  } catch (error) {
    if (error instanceof ValidationError) {
      return NextResponse.json({ error: error.message }, { status: 400 });
    }
    if (error instanceof AuthenticationError) {
      return NextResponse.json({ error: 'Invalid API key.' }, { status: 401 });
    }
    if (error instanceof FeatureRestrictedError) {
      return NextResponse.json(
        { error: error.message, requiredPlan: error.requiredPlan, upgradeUrl: error.upgradeUrl },
        { status: 403 }
      );
    }
    if (error instanceof RateLimitError) {
      return NextResponse.json({ error: error.message }, { status: 429 });
    }
    return NextResponse.json({ error: 'Search failed. Please try again.' }, { status: 502 });
  }
}
`;
}

