export function generateAutocompleteComponentNextjs(): string {
  return `// components/LocationAutocomplete.tsx
// Generated by @countrystatecity/cli
// Calls the same-origin /api/csc-search route — see ${AUTOCOMPLETE_ROUTE_PATH}.
// The API key never reaches this file or the browser.
'use client';

${HOOK_IMPORTS}
import type { IAutocompleteResult, SearchResultType } from '@countrystatecity/sdk';

export interface LocationAutocompleteProps {
  /** Entity type to search. Defaults to 'city'. */
  type?: SearchResultType;
  /** Restrict results to this country (ISO2), when type is 'state' or 'city'. */
  country?: string;
  /** Restrict results to this state (ISO2). Requires \`country\`. */
  state?: string;
  placeholder?: string;
  /** Called with the full, typed result on selection — use its id/iso2/
   * country_code/state_code as the stable identifier, never \`label\`. */
  onSelect?: (result: IAutocompleteResult) => void;
  className?: string;
}

type Status = 'idle' | 'loading' | 'success' | 'empty' | 'plan-restricted' | 'rate-limited' | 'network-error';

const MIN_QUERY_LENGTH = 2;
const DEBOUNCE_MS = 250;
const UPGRADE_URL = '${TRACKED_PRICING_URL}';

export default function LocationAutocomplete({
  type = 'city',
  country,
  state,
  placeholder = 'Search for a place…',
  onSelect,
  className = '',
}: LocationAutocompleteProps) {
  const [query, setQuery] = useState('');
  const [results, setResults] = useState<IAutocompleteResult[]>([]);
  const [status, setStatus] = useState<Status>('idle');
  const [planMessage, setPlanMessage] = useState<string | null>(null);
  const [isOpen, setIsOpen] = useState(false);
  const [activeIndex, setActiveIndex] = useState(-1);

  const debounceRef = useRef<ReturnType<typeof setTimeout> | null>(null);
  const abortRef = useRef<AbortController | null>(null);
  const listboxId = useId();

  const runSearch = useCallback((q: string) => {
    abortRef.current?.abort();

    if (q.trim().length < MIN_QUERY_LENGTH) {
      setResults([]);
      setStatus('idle');
      setIsOpen(false);
      return;
    }

    const controller = new AbortController();
    abortRef.current = controller;
    setStatus('loading');
    setResults([]);
    setIsOpen(false);
    setActiveIndex(-1);

    const params = new URLSearchParams({ query: q, type });
    if (country) params.set('country', country);
    if (state) params.set('state', state);

    fetch(\`/api/csc-search?\${params.toString()}\`, { signal: controller.signal })
      .then(async (res) => {
        if (controller.signal.aborted) return;
        if (res.status === 403) {
          const body = await res.json().catch(() => null);
          setPlanMessage(body?.error ?? null);
          setStatus('plan-restricted');
          setResults([]);
          return;
        }
        if (res.status === 429) {
          setStatus('rate-limited');
          setResults([]);
          return;
        }
        if (!res.ok) {
          setStatus('network-error');
          setResults([]);
          return;
        }
        const data: IAutocompleteResult[] = await res.json();
        if (controller.signal.aborted) return;
        setResults(data);
        setStatus(data.length === 0 ? 'empty' : 'success');
        setActiveIndex(-1);
        setIsOpen(true);
      })
      .catch((err) => {
        if (err instanceof DOMException && err.name === 'AbortError') return;
        setStatus('network-error');
        setResults([]);
      });
  }, [type, country, state]);

  useEffect(() => {
    return () => {
      abortRef.current?.abort();
      if (debounceRef.current) clearTimeout(debounceRef.current);
    };
  }, []);

  useEffect(() => {
    abortRef.current?.abort();
    if (debounceRef.current) clearTimeout(debounceRef.current);
    debounceRef.current = null;
    setQuery('');
    setResults([]);
    setStatus('idle');
    setIsOpen(false);
    setActiveIndex(-1);
  }, [type, country, state]);

  function handleChange(e: React.ChangeEvent<HTMLInputElement>) {
    const value = e.target.value;
    setQuery(value);

    if (debounceRef.current) clearTimeout(debounceRef.current);
    debounceRef.current = setTimeout(() => runSearch(value), DEBOUNCE_MS);
  }

  function selectResult(result: IAutocompleteResult) {
    if (debounceRef.current) clearTimeout(debounceRef.current);
    debounceRef.current = null;
    abortRef.current?.abort();
    abortRef.current = null;
    setQuery(result.label);
    setIsOpen(false);
    setResults([]);
    setStatus('idle');
    onSelect?.(result);
  }

${KEYBOARD_HANDLER}

  const activeDescendant = activeIndex >= 0 ? \`\${listboxId}-option-\${activeIndex}\` : undefined;

  return (
    <div className={\`csc-field \${className}\`} style={{ position: 'relative' }}>
      <input
        type="text"
        role="combobox"
        aria-expanded={isOpen}
        aria-controls={listboxId}
        aria-autocomplete="list"
        aria-activedescendant={activeDescendant}
        aria-label={placeholder}
        value={query}
        placeholder={placeholder}
        onChange={handleChange}
        onKeyDown={handleKeyDown}
        onFocus={() => { if (results.length > 0) setIsOpen(true); }}
        onBlur={() => setTimeout(() => setIsOpen(false), 150)}
        autoComplete="off"
      />

${statusBlock('      ')}

${listboxBlock('      ')}
    </div>
  );
}
`;
}

