const HOOK_IMPORTS = `import { useCallback, useEffect, useId, useRef, useState } from 'react';`;

function statusBlock(indent: string): string {
  return `${indent}{status === 'loading' && (
${indent}  <div role="status" className="csc-field-status">Searching…</div>
${indent})}
${indent}{status === 'plan-restricted' && (
${indent}  <div role="alert" className="csc-field-status csc-field-error">
${indent}    {planMessage ?? 'This search requires a higher plan. Upgrade to enable it.'}
${indent}    {' '}<a href={UPGRADE_URL} target="_blank" rel="noreferrer">View API plans</a>
${indent}  </div>
${indent})}
${indent}{status === 'rate-limited' && (
${indent}  <div role="alert" className="csc-field-status csc-field-error">
${indent}    Too many requests — please slow down and try again shortly.
${indent}  </div>
${indent})}
${indent}{status === 'network-error' && (
${indent}  <div role="alert" className="csc-field-status csc-field-error">
${indent}    Couldn't reach the search service. Check your connection and try again.
${indent}  </div>
${indent})}
${indent}{status === 'empty' && (
${indent}  <div role="status" className="csc-field-status">No results found.</div>
${indent})}`;
}

function listboxBlock(indent: string): string {
  return `${indent}{isOpen && results.length > 0 && (
${indent}  <ul id={listboxId} role="listbox" className="csc-field-list">
${indent}    {results.map((result, index) => (
${indent}      <li
${indent}        key={\`\${result.type}-\${'iso2' in result ? result.iso2 : result.id}-\${index}\`}
${indent}        id={\`\${listboxId}-option-\${index}\`}
${indent}        role="option"
${indent}        aria-selected={index === activeIndex}
${indent}        className={index === activeIndex ? 'active' : ''}
${indent}        onMouseDown={(e) => { e.preventDefault(); selectResult(result); }}
${indent}      >
${indent}        {result.label}
${indent}      </li>
${indent}    ))}
${indent}  </ul>
${indent})}`;
}

const KEYBOARD_HANDLER = `  function handleKeyDown(e: React.KeyboardEvent<HTMLInputElement>) {
    if (!isOpen || results.length === 0) return;

    if (e.key === 'ArrowDown') {
      e.preventDefault();
      setActiveIndex((i) => (i + 1) % results.length);
    } else if (e.key === 'ArrowUp') {
      e.preventDefault();
      setActiveIndex((i) => (i <= 0 ? results.length - 1 : i - 1));
    } else if (e.key === 'Enter') {
      if (activeIndex >= 0) {
        e.preventDefault();
        selectResult(results[activeIndex]);
      }
    } else if (e.key === 'Escape') {
      setIsOpen(false);
      setActiveIndex(-1);
    } else if (e.key === 'Tab') {
      setIsOpen(false);
    }
  }`;

